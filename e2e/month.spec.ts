import { MAKKAH, expect, navTo, open, pickCity, test, withLocation, withUmmAlQura } from './fixtures'

test.use({ timezoneId: 'Asia/Riyadh' })

test('monthly navigation handles leap February, year rollover, today and narrow screens', async ({ page }) => {
  await page.clock.install({ time: new Date('2024-01-31T10:00:00+03:00') })
  await withLocation(page, MAKKAH.latitude, MAKKAH.longitude, MAKKAH.label)
  await open(page)
  await page.getByRole('button', { name: 'Monthly timetable' }).click()
  const rows = page.locator('tbody tr')
  await expect(page.getByRole('heading', { name: 'January 2024' })).toBeVisible()
  await expect(rows).toHaveCount(31)
  await expect(page.locator('tr[aria-current=date]')).toContainText('Jan 31')
  await expect(page.getByText(MAKKAH.label, { exact: true })).toBeVisible()
  await expect(page.getByRole('columnheader')).toHaveCount(7)
  await page.getByRole('button', { name: 'Previous month' }).click()
  await expect(page.getByRole('heading', { name: 'December 2023' })).toBeVisible()
  await expect(page.locator('tr[aria-current=date]')).toHaveCount(0)
  await page.getByRole('button', { name: 'Next month' }).click()
  await page.getByRole('button', { name: 'Next month' }).click()
  await expect(page.getByRole('heading', { name: 'February 2024' })).toBeVisible()
  await expect(rows).toHaveCount(29)
  await page.getByRole('button', { name: 'Next month' }).click()
  await expect(rows).toHaveCount(31)
  await page.getByRole('button', { name: 'Next month' }).click()
  await expect(rows).toHaveCount(30)
  await page.getByRole('button', { name: 'Current month' }).click()
  await expect(page.getByRole('heading', { name: 'January 2024' })).toBeVisible()
  const region = page.getByRole('region', { name: 'Monthly prayer times' })
  await region.evaluate(el => el.scrollBy({ left: 1000 }))
  await expect(page.getByRole('columnheader', { name: /^Isha/ })).toBeInViewport()
  await expect(rows.first().getByRole('rowheader')).toBeInViewport()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
})

test('monthly view uses changed settings and location', async ({ page }) => {
  await page.clock.install({ time: new Date('2016-06-04T10:00:00+03:00') })
  await withLocation(page, MAKKAH.latitude, MAKKAH.longitude, MAKKAH.label)
  await withUmmAlQura(page)
  await open(page, '/month')
  await expect(page.locator('tr[aria-current=date]')).toContainText('4:11 AM')
  await navTo(page, 'Settings')
  await page.getByLabel('Fajr', { exact: true }).fill('5')
  await navTo(page, 'Monthly')
  await expect(page.locator('tr[aria-current=date]')).toContainText('4:16 AM')
  await navTo(page, 'Settings')
  await page.getByLabel('Calculation method').selectOption('Singapore')
  await page.getByLabel('Hanafi').check()
  await page.getByLabel('High-latitude rule').selectOption('seventhofthenight')
  await navTo(page, 'Today')
  const fajr = await page.getByRole('listitem').filter({ hasText: /^Fajr/ }).locator('span[dir=ltr]').innerText()
  await navTo(page, 'Monthly')
  await expect(page.locator('tr[aria-current=date]')).toContainText(fajr)
  await navTo(page, 'Settings')
  await pickCity(page, 'London', /London/)
  await navTo(page, 'Monthly')
  await expect(page.getByRole('main')).toContainText('London')
  await expect(page.locator('tr[aria-current=date]')).not.toContainText(fajr)
})

test('monthly view offers location setup when no location is saved', async ({ page }) => {
  await open(page, '/month')
  await expect(page.getByRole('table')).toHaveCount(0)
  await page.getByRole('button', { name: 'Set location', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Settings', exact: true })).toBeVisible()
})
